"""API endpoints for Store Analyst agent, daily briefings, and HITL action proposals."""

import uuid
from typing import Annotated

from fastapi import APIRouter, Depends, Query
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from omnimission.agents.store_analyst import (
    ActionProposalResponse,
    AnalystResponse,
    StoreAnalystAgent,
)
from omnimission.core.deps import require_merchant
from omnimission.db.session import get_db_session
from omnimission.models.user import User
from omnimission.services.action_proposal_service import ActionProposalService
from omnimission.services.briefing_service import DailyBriefingResponse, DailyBriefingService

router = APIRouter(prefix="/merchant", tags=["Merchant Analyst"])


class AnalystQueryRequest(BaseModel):
    """Payload to ask natural-language business questions to Store Analyst."""

    query: str = Field(..., min_length=2, max_length=500, description="Natural language prompt")
    store_id: uuid.UUID = Field(..., description="Target physical store UUID")


class ProposalDecisionRequest(BaseModel):
    """Payload to approve or reject a pending proposal."""

    decision_note: str | None = Field(None, max_length=500, description="Optional merchant note")


def get_analyst_agent() -> StoreAnalystAgent:
    return StoreAnalystAgent()


def get_briefing_service() -> DailyBriefingService:
    return DailyBriefingService()


def get_proposal_service() -> ActionProposalService:
    return ActionProposalService()


@router.post(
    "/analyst/query",
    response_model=AnalystResponse,
    summary="Query Store Analyst with natural language (Guarded NL2SQL)",
)
async def query_store_analyst(
    payload: AnalystQueryRequest,
    current_user: Annotated[User, Depends(require_merchant)],
    session: Annotated[AsyncSession, Depends(get_db_session)],
    agent: Annotated[StoreAnalystAgent, Depends(get_analyst_agent)],
) -> AnalystResponse:
    """Execute natural-language question with AST-guarded SQL and chart visualization."""
    return await agent.analyze(
        session=session,
        query=payload.query,
        store_id=payload.store_id,
        merchant_id=current_user.id,
    )


@router.get(
    "/analyst/briefing",
    response_model=DailyBriefingResponse,
    summary="Get proactive daily briefing for physical store",
)
async def get_daily_briefing(
    store_id: uuid.UUID = Query(..., description="Store UUID"),
    _current_user: User = Depends(require_merchant),
    session: AsyncSession = Depends(get_db_session),
    briefing_service: DailyBriefingService = Depends(get_briefing_service),
) -> DailyBriefingResponse:
    """Retrieve operational morning briefing with KPIs, stockout warnings, and proposal counts."""
    return await briefing_service.generate_briefing(
        session=session,
        store_id=store_id,
    )


@router.get(
    "/proposals",
    response_model=list[ActionProposalResponse],
    summary="List action proposals for store",
)
async def list_proposals(
    store_id: uuid.UUID = Query(..., description="Store UUID"),
    status: str | None = Query(None, description="Optional status filter"),
    _current_user: User = Depends(require_merchant),
    session: AsyncSession = Depends(get_db_session),
    proposal_service: ActionProposalService = Depends(get_proposal_service),
) -> list[ActionProposalResponse]:
    """List pending or reviewed proposals generated by Store Analyst."""
    proposals = await proposal_service.list_proposals(session, store_id, status=status)
    return [
        ActionProposalResponse(
            id=str(p.id),
            action_type=p.action_type,
            title=p.title,
            description=p.description,
            payload=p.payload,
            status=p.status,
        )
        for p in proposals
    ]


@router.post(
    "/proposals/{proposal_id}/approve",
    response_model=ActionProposalResponse,
    summary="Approve and execute an action proposal (HITL)",
)
async def approve_proposal(
    proposal_id: uuid.UUID,
    payload: ProposalDecisionRequest,
    current_user: Annotated[User, Depends(require_merchant)],
    session: Annotated[AsyncSession, Depends(get_db_session)],
    proposal_service: Annotated[ActionProposalService, Depends(get_proposal_service)],
) -> ActionProposalResponse:
    """Approve proposal, triggering the associated business action."""
    prop = await proposal_service.approve_proposal(
        session=session,
        proposal_id=proposal_id,
        user_id=current_user.id,
        decision_note=payload.decision_note,
    )
    await session.commit()
    return ActionProposalResponse(
        id=str(prop.id),
        action_type=prop.action_type,
        title=prop.title,
        description=prop.description,
        payload=prop.payload,
        status=prop.status,
    )


@router.post(
    "/proposals/{proposal_id}/reject",
    response_model=ActionProposalResponse,
    summary="Reject an action proposal (HITL)",
)
async def reject_proposal(
    proposal_id: uuid.UUID,
    payload: ProposalDecisionRequest,
    current_user: Annotated[User, Depends(require_merchant)],
    session: Annotated[AsyncSession, Depends(get_db_session)],
    proposal_service: Annotated[ActionProposalService, Depends(get_proposal_service)],
) -> ActionProposalResponse:
    """Reject proposal, archiving it with merchant note."""
    prop = await proposal_service.reject_proposal(
        session=session,
        proposal_id=proposal_id,
        user_id=current_user.id,
        decision_note=payload.decision_note,
    )
    await session.commit()
    return ActionProposalResponse(
        id=str(prop.id),
        action_type=prop.action_type,
        title=prop.title,
        description=prop.description,
        payload=prop.payload,
        status=prop.status,
    )
